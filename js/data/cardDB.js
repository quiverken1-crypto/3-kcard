/* ---------------------------------------------------------------- 构建 */
function build(rows, kingdom) {
  return rows.map(r => {
    const [id, name, t, troop, cost, act, atk, hp, keywords, badges, skillName, desc, copies, inferred] = r;
    const type = TYPE[t];
    return Object.freeze({
      id, cardId: id, name, kingdom, faction: kingdom.toUpperCase(),
      type, troopType: TROOP[troop], troop_type: TROOP[troop].toLowerCase(),
      cost, actionCost: act, action_cost: act, atk, attack: atk, hp, maxHp: hp, max_hp: hp,
      keywords: [...keywords], badges: [...badges],
      skill: { name: skillName || name, description: desc || '' },
      copies, inferred: inferred || '', ...(/待实现/.test(inferred || '') ? { pending: true } : {}), isDefector: keywords.includes('降将')
    });
  });
}

const markExtra = (cards, label = '旧图鉴') => cards.map(c => Object.freeze({ ...c, extra: true, extraLabel: label }));

